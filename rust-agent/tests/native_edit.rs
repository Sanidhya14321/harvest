//! The native application must preserve file encoding and reject unsafe
//! edits. Edits use the hashline contract: `read` records the snapshot whose
//! `[path#TAG]` header anchors the `edit` input.
use std::path::Path;

use anyhow::Result;
use harvest_omp::{
	chat::{FunctionCall, ToolCall},
	tools::{Approval, invoke, invoke_with_cancellation, invoke_with_store},
};
use harvest_runtime::{MAX_FILE_BYTES, cancel::CancelToken};
use serde_json::json;

struct Allow;
impl Approval for Allow {
	fn approve(&self, _: &ToolCall) -> Result<bool> {
		Ok(true)
	}
}

fn tool(name: &str, arguments: serde_json::Value) -> ToolCall {
	ToolCall {
		id:       "edit-contract".into(),
		kind:     "function".into(),
		function: FunctionCall { name: name.into(), arguments: arguments.to_string() },
	}
}

/// Read `path` and replace its line `line` (1-based) with `new`, via the
/// tag the read returned. `new` may contain several lines.
fn edit_line(root: &Path, path: &str, line: usize, new: &str) -> Result<String> {
	let store = pi_edit::EditStore::new();
	let read = invoke_with_store(
		root,
		&tool("read", json!({"path": path})),
		&Allow,
		&CancelToken::default(),
		&store,
	)?;
	let header = read.lines().next().unwrap_or_default().to_owned();
	let body = new
		.lines()
		.map(|row| format!("+{row}\n"))
		.collect::<Vec<_>>()
		.concat();
	let input = format!("{header}\nPUT {line}.={line}:\n{body}");
	invoke_with_store(
		root,
		&tool("edit", json!({"input": input})),
		&Allow,
		&CancelToken::default(),
		&store,
	)
}

fn call(path: &str) -> ToolCall {
	tool("edit", json!({"input": format!("[{path}#0000]\nPUT 1.=1:\n+changed\n")}))
}

#[test]
fn normalized_multiline_edit_preserves_utf8_bom_and_crlf() -> Result<()> {
	let root = tempfile::tempdir()?;
	let path = root.path().join("encoded.txt");
	std::fs::write(&path, "\u{feff}alpha\r\nbeta\r\n")?;
	edit_line(root.path(), "encoded.txt", 1, "gamma")?;
	edit_line(root.path(), "encoded.txt", 2, "delta")?;
	assert_eq!(std::fs::read(&path)?, "\u{feff}gamma\r\ndelta\r\n".as_bytes());
	Ok(())
}

#[test]
fn editing_notebook_source_preserves_other_cells_and_notebook_metadata() -> Result<()> {
	let root = tempfile::tempdir()?;
	let path = root.path().join("notes.ipynb");
	let before = json!({"nbformat":4,"nbformat_minor":5,"metadata":{"owner":"user"},"cells":[
		{"cell_type":"code","metadata":{},"source":["print(1)\n"],"outputs":[],"execution_count":null},
		{"cell_type":"markdown","metadata":{"tag":"keep"},"source":["Keep this cell\n"]}
	]});
	std::fs::write(&path, serde_json::to_vec(&before)?)?;
	let read = invoke_with_store(
		root.path(),
		&tool("read", json!({"path":"notes.ipynb"})),
		&Allow,
		&CancelToken::default(),
		&pi_edit::EditStore::new(),
	)?;
	let line = read
		.lines()
		.find_map(|row| {
			row.strip_suffix(":print(1)")
				.and_then(|number| number.parse::<usize>().ok())
		})
		.expect("notebook view shows the code cell");
	edit_line(root.path(), "notes.ipynb", line, "print(2)")?;
	let after: serde_json::Value = serde_json::from_slice(&std::fs::read(&path)?)?;
	assert_eq!(after["cells"][0]["source"], json!(["print(2)\n"]));
	assert_eq!(after["cells"][1], before["cells"][1]);
	assert_eq!(after["metadata"], before["metadata"]);
	Ok(())
}

#[test]
fn stale_tags_and_generated_targets_remain_unchanged() -> Result<()> {
	let root = tempfile::tempdir()?;
	let path = root.path().join("file.txt");
	std::fs::write(&path, "one\n")?;
	assert!(
		invoke_with_cancellation(root.path(), &call("file.txt"), &Allow, &CancelToken::default())
			.is_err()
	);
	assert_eq!(std::fs::read_to_string(&path)?, "one\n");
	let generated = root.path().join("generated.ts");
	std::fs::write(&generated, "// @generated by protoc\nconst one = 1;\n")?;
	let error = edit_line(root.path(), "generated.ts", 2, "const two = 2;").unwrap_err();
	assert!(error.to_string().contains("auto-generated"), "{error}");
	assert_eq!(std::fs::read_to_string(&generated)?, "// @generated by protoc\nconst one = 1;\n");
	Ok(())
}

#[test]
fn invalid_utf8_and_oversized_files_are_rejected_without_data_loss() -> Result<()> {
	let root = tempfile::tempdir()?;
	let path = root.path().join("invalid.txt");
	std::fs::write(&path, [b'a', 0xff])?;
	assert!(
		edit_line(root.path(), "invalid.txt", 1, "b")
			.unwrap_err()
			.to_string()
			.contains("UTF-8")
	);
	assert_eq!(std::fs::read(&path)?, [b'a', 0xff]);
	let large = root.path().join("large.txt");
	let bytes = vec![b'a'; MAX_FILE_BYTES + 1];
	std::fs::write(&large, &bytes)?;
	assert!(edit_line(root.path(), "large.txt", 1, "b").is_err());
	assert_eq!(std::fs::read(&large)?, bytes);
	Ok(())
}

#[test]
fn denied_or_cancelled_edit_does_not_modify_the_target() -> Result<()> {
	let root = tempfile::tempdir()?;
	let path = root.path().join("file.txt");
	std::fs::write(&path, "before\n")?;
	let request = call("file.txt");
	assert!(invoke(root.path(), &request).is_err());
	let mut token = CancelToken::default();
	token
		.emplace_abort_token()
		.abort(harvest_runtime::cancel::AbortReason::User);
	assert!(invoke_with_cancellation(root.path(), &request, &Allow, &token).is_err());
	assert_eq!(std::fs::read_to_string(&path)?, "before\n");
	Ok(())
}

#[cfg(unix)]
#[test]
fn symlinked_targets_and_missing_leaves_under_escaping_parents_are_rejected() -> Result<()> {
	let root = tempfile::tempdir()?;
	let outside = tempfile::tempdir()?;
	let secret = outside.path().join("secret.txt");
	std::fs::write(&secret, "secret\n")?;
	std::os::unix::fs::symlink(outside.path(), root.path().join("escape"))?;
	assert!(edit_line(root.path(), "escape/secret.txt", 1, "changed").is_err());
	let tag = pi_edit::store::file_hash("secret\n");
	for target in ["escape/secret.txt", "escape/missing.txt"] {
		let input = format!("[{target}#{tag}]\nPUT 1.=1:\n+changed\n");
		let request = tool("edit", json!({"input": input}));
		assert!(
			invoke_with_cancellation(root.path(), &request, &Allow, &CancelToken::default()).is_err()
		);
	}
	assert_eq!(std::fs::read_to_string(&secret)?, "secret\n");
	assert!(!outside.path().join("missing.txt").exists());
	Ok(())
}
